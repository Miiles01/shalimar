"""Writes the menu into index.html as static HTML (tabs + panels) and refreshes
the Restaurant / Menu JSON-LD, so crawlers see every dish without running JS.

Run from the project root after editing _source/menu.json:
    python3 _source/build_menu.py
"""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://shalimarmeal.com/"
PHOTOS = {
    "soups": "gosht", "fried-rice": "rice-plate", "noodles": "noodles",
    "tandoor": "tandoor", "biryani": "biryani-plate", "specials": "specials",
    "sides": "sides", "bread": "bread", "drinks": "drinks",
}

data = json.loads((ROOT / "_source/menu.json").read_text())
cats = data["categories"]
esc = html.escape


def dish_html(item, i):
    name = esc(item["name"])
    tag = '<span class="dish__tag"><span class="star" aria-hidden="true"></span>house favourite</span>' if item.get("signature") else ""
    ar = f'<p class="dish__ar" lang="ar" dir="rtl">{esc(item["ar"])}</p>' if item.get("ar") else ""
    if "prices" in item:
        price = '<p class="dish__variants">' + "".join(
            f"<span><em>{esc(k)}</em> SAR {v}</span>" for k, v in item["prices"].items()) + "</p>"
    else:
        price = f'<p class="dish__variants"><span>SAR {item["price"]}</span></p>' if item.get("price") is not None else '<p class="dish__variants"><span>Ask us</span></p>'
    desc = f'<p class="dish__desc">{esc(item["desc"])}</p>' if item.get("desc") else ""
    kcal = f'<p class="dish__kcal">{item["kcal"]} kcal</p>' if item.get("kcal") else ""
    return (f'<article class="dish" style="--i:{min(i, 12)}"><h4 class="dish__name">{name}{tag}</h4>{ar}'
            f'{desc}{price}{kcal}</article>')


tabs, panels = [], []
for n, c in enumerate(cats):
    cid, first = c["id"], n == 0
    photo = f"assets/img/{PHOTOS[cid]}.jpg"
    tabs.append(
        f'<button class="t-tab" type="button" role="tab" id="tab-{cid}" aria-controls="panel-{cid}" '
        f'aria-selected="{"true" if first else "false"}" tabindex="{0 if first else -1}" data-photo="{photo}">{esc(c["name"])}</button>')
    items = "\n            ".join(dish_html(it, i) for i, it in enumerate(c["items"]))
    panels.append(
        f'<div class="menu__list" role="tabpanel" id="panel-{cid}" aria-labelledby="tab-{cid}" tabindex="0" data-panel{"" if first else " hidden"}>\n'
        f'            <h3 class="menu__cat"><span>{esc(c["name"])}</span><span class="menu__cat-ar" lang="ar" dir="rtl">{esc(c["ar"])}</span></h3>\n            {items}\n          </div>')

block = (
    '<!-- menu:start (generated by _source/build_menu.py) -->\n'
    '      <div class="menu__tabs-wrap reveal-up">\n'
    '        <div class="t-tabs" role="tablist" aria-label="Menu categories" data-tabs>\n'
    '          <span class="t-tabs-pill" aria-hidden="true"></span>\n          '
    + "\n          ".join(tabs) +
    '\n        </div>\n      </div>\n'
    '      <div class="menu__body">\n'
    f'        <figure class="menu__photo"><img data-menu-photo src="assets/img/{PHOTOS[cats[0]["id"]]}.jpg" alt="{esc(cats[0]["name"])} at Shalimar Restaurant" width="730" height="350" loading="lazy"></figure>\n'
    '        <div class="menu__panels">\n          '
    + "\n          ".join(panels) +
    '\n        </div>\n      </div>\n'
    '      <!-- menu:end -->')


def offers(item):
    if "prices" in item:
        return [{"@type": "Offer", "name": k, "price": v, "priceCurrency": "SAR"} for k, v in item["prices"].items()]
    if item.get("price") is not None:
        return {"@type": "Offer", "price": item["price"], "priceCurrency": "SAR"}
    return None


def menu_item(item):
    o = {"@type": "MenuItem", "name": item["name"]}
    if item.get("ar"):
        o["alternateName"] = item["ar"]
    if item.get("desc"):
        o["description"] = item["desc"]
    if offers(item):
        o["offers"] = offers(item)
    if item.get("kcal"):
        o["nutrition"] = {"@type": "NutritionInformation", "calories": f'{item["kcal"]} calories'}
    return o


ld = {
    "@context": "https://schema.org",
    "@graph": [
        {
            "@type": "Restaurant",
            "@id": SITE + "#restaurant",
            "name": "Shalimar Restaurant",
            "alternateName": "مطعم شاليمار",
            "description": "Authentic Indian cuisine at wallet-friendly prices since 2014: butter chicken, biryani, tandoori, curries and fresh naan.",
            "url": SITE,
            "image": [SITE + "assets/img/og-image.jpg", SITE + "assets/img/platter.jpg", SITE + "assets/img/biryani.jpg"],
            "logo": SITE + "assets/img/favicon.svg",
            "telephone": "+966549196656",
            "email": "info@shalimarmeal.com",
            "foundingDate": "2014",
            "servesCuisine": ["Indian", "North Indian", "Biryani", "Tandoori", "Curry"],
            "priceRange": "SAR 1–65",
            "currenciesAccepted": "SAR",
            "acceptsReservations": True,
            "address": {"@type": "PostalAddress", "addressCountry": "SA"},
            "openingHoursSpecification": [{
                "@type": "OpeningHoursSpecification",
                "dayOfWeek": ["Saturday", "Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday"],
                "opens": "11:00", "closes": "00:30",
            }],
            "sameAs": ["https://www.facebook.com/ShalimarRestaurantasu", "https://twitter.com/shalimarasu"],
            "hasMenu": {"@id": SITE + "#menu"},
        },
        {
            "@type": "Menu",
            "@id": SITE + "#menu",
            "name": "Shalimar Restaurant menu",
            "url": SITE + "#menu",
            "inLanguage": "en",
            "hasMenuSection": [
                {"@type": "MenuSection", "name": c["name"], "alternateName": c["ar"], "hasMenuItem": [menu_item(it) for it in c["items"]]}
                for c in cats
            ],
        },
        {
            "@type": "WebSite",
            "@id": SITE + "#website",
            "url": SITE,
            "name": "Shalimar Restaurant",
            "inLanguage": "en",
            "publisher": {"@id": SITE + "#restaurant"},
        },
    ],
}

page = ROOT / "index.html"
s = page.read_text()
s = re.sub(r"<!-- menu:start.*?<!-- menu:end -->", lambda _: block, s, flags=re.S)
s = re.sub(r'<script type="application/ld\+json">.*?</script>',
           lambda _: '<script type="application/ld+json">\n' + json.dumps(ld, ensure_ascii=False, indent=1) + '\n  </script>',
           s, count=1, flags=re.S)
page.write_text(s)
print(f"{sum(len(c['items']) for c in cats)} dishes in {len(cats)} sections written to index.html")
