"""Writes the menu into index.html as static HTML (tabs + panels) and refreshes
the Restaurant / Menu JSON-LD, so crawlers see every dish without running JS.

Run from the project root after editing _source/menu.json:
    python3 _source/build_menu.py
"""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://restaurantshalimar.ca/"
PHOTOS = {
    "combos": "ca/menu-combos", "starters": "ca/menu-starters", "curries": "ca/menu-curries",
    "tandoori": "ca/menu-tandoori", "vegetarian": "ca/menu-vegetarian", "biryani": "ca/menu-biryani",
    "breads": "ca/menu-tandoori", "desserts": "ca/menu-drinks",
}

data = json.loads((ROOT / "_source/menu.json").read_text())
cats = data["categories"]
esc = html.escape


def money(v):
    return f"${v:.2f}"


def dish_html(item, i):
    tags = ""
    if item.get("signature"):
        tags += '<span class="dish__tag"><span class="star" aria-hidden="true"></span>house favourite</span>'
    if item.get("isNew"):
        tags += '<span class="dish__tag dish__tag--new">new</span>'
    hi = f'<p class="dish__hi" lang="hi">{esc(item["hi"])}</p>' if item.get("hi") else ""
    if item.get("dineIn"):
        price = '<p class="dish__variants"><span><em>Dine-in only</em></span></p>'
    else:
        unit = f' <em>/ {esc(item["unit"])}</em>' if item.get("unit") else ""
        price = f'<p class="dish__variants"><span>{money(item["price"])}{unit}</span></p>'
    desc = f'<p class="dish__desc">{esc(item["desc"])}</p>' if item.get("desc") else ""
    return (f'<article class="dish" style="--i:{min(i, 12)}"><h4 class="dish__name">{esc(item["name"])}{tags}</h4>{hi}'
            f'{desc}{price}</article>')


tabs, panels = [], []
for n, c in enumerate(cats):
    cid, first = c["id"], n == 0
    photo = f"assets/img/{PHOTOS[cid]}.jpg"
    tabs.append(
        f'<button class="t-tab" type="button" role="tab" id="tab-{cid}" aria-controls="panel-{cid}" '
        f'aria-selected="{"true" if first else "false"}" tabindex="{0 if first else -1}" data-photo="{photo}">{esc(c["name"])}</button>')
    items = "\n            ".join(dish_html(it, i) for i, it in enumerate(c["items"]))
    panels.append(
        f'<div class="menu__list" role="tabpanel" id="panel-{cid}" aria-labelledby="tab-{cid}" tabindex="0" data-panel{"" if first else " hidden"}>\n'
        f'            <h3 class="menu__cat"><span>{esc(c["name"])}</span><span class="menu__cat-hi" lang="hi">{esc(c["hi"])}</span></h3>\n            {items}\n          </div>')

block = (
    '<!-- menu:start (generated by _source/build_menu.py) -->\n'
    '      <div class="menu__tabs-wrap reveal-up">\n'
    '        <div class="t-tabs" role="tablist" aria-label="Menu categories" data-tabs>\n'
    '          <span class="t-tabs-pill" aria-hidden="true"></span>\n          '
    + "\n          ".join(tabs) +
    '\n        </div>\n      </div>\n'
    '      <div class="menu__body">\n'
    f'        <figure class="menu__photo reveal-img"><img data-menu-photo src="assets/img/{PHOTOS[cats[0]["id"]]}.jpg" alt="{esc(cats[0]["name"])} at Restaurant Shalimar" width="1200" height="1200" loading="lazy"></figure>\n'
    '        <div class="menu__panels">\n          '
    + "\n          ".join(panels) +
    '\n        </div>\n      </div>\n'
    '      <!-- menu:end -->')


def menu_item(item):
    o = {"@type": "MenuItem", "name": item["name"]}
    if item.get("hi"):
        o["alternateName"] = item["hi"]
    if item.get("desc"):
        o["description"] = item["desc"]
    if item.get("price") is not None:
        o["offers"] = {"@type": "Offer", "price": f'{item["price"]:.2f}', "priceCurrency": "CAD"}
    return o


ld = {
    "@context": "https://schema.org",
    "@graph": [
        {
            "@type": "Restaurant",
            "@id": SITE + "#restaurant",
            "name": "Restaurant Shalimar",
            "description": "Authentic Indian cuisine in Sherbrooke since 1990, beginning with fresh local ingredients: butter chicken, tandoori, biryani, vegetarian and vegan dishes, with vegetables grown in our own organic garden.",
            "url": SITE,
            "image": [SITE + "assets/img/og-image.jpg", SITE + "assets/img/ca/dining-room.jpg", SITE + "assets/img/ca/tandoori-platter.jpg"],
            "logo": SITE + "assets/img/ca/logo.png",
            "telephone": "+1-819-823-9683",
            "foundingDate": "1990",
            "founder": {"@type": "Person", "name": "Uma Nigam"},
            "servesCuisine": ["Indian", "North Indian", "South Indian", "Vegetarian", "Vegan"],
            "priceRange": "$$",
            "currenciesAccepted": "CAD",
            "acceptsReservations": "True",
            "address": {"@type": "PostalAddress", "streetAddress": "263 Queen Street", "addressLocality": "Sherbrooke", "addressRegion": "QC", "postalCode": "J1M 1K8", "addressCountry": "CA"},
            "geo": {"@type": "GeoCoordinates", "latitude": 45.375018, "longitude": -71.862245},
            "hasMap": "https://www.google.ca/maps/place/Restaurant+Shalimar/@45.375018,-71.862245,17z",
            "openingHoursSpecification": [
                {"@type": "OpeningHoursSpecification", "dayOfWeek": ["Wednesday", "Thursday"], "opens": "17:30", "closes": "21:00"},
                {"@type": "OpeningHoursSpecification", "dayOfWeek": "Friday", "opens": "11:00", "closes": "14:00"},
                {"@type": "OpeningHoursSpecification", "dayOfWeek": ["Friday", "Saturday"], "opens": "17:30", "closes": "22:00"},
            ],
            "hasMenu": {"@id": SITE + "#menu"},
        },
        {
            "@type": "Menu",
            "@id": SITE + "#menu",
            "name": "Restaurant Shalimar take-out menu",
            "url": SITE + "#menu",
            "inLanguage": "en",
            "hasMenuSection": [
                {"@type": "MenuSection", "name": c["name"], "hasMenuItem": [menu_item(it) for it in c["items"]]}
                for c in cats
            ],
        },
        {
            "@type": "WebSite",
            "@id": SITE + "#website",
            "url": SITE,
            "name": "Restaurant Shalimar",
            "inLanguage": "en",
            "publisher": {"@id": SITE + "#restaurant"},
        },
    ],
}

page = ROOT / "index.html"
s = page.read_text()
s = re.sub(r"<!-- menu:start.*?<!-- menu:end -->", lambda _: block, s, flags=re.S)
s = re.sub(r'<script type="application/ld\+json">.*?</script>',
           lambda _: '<script type="application/ld+json">\n' + json.dumps(ld, ensure_ascii=False, indent=1) + '\n  </script>',
           s, count=1, flags=re.S)
page.write_text(s)
print(f"{sum(len(c['items']) for c in cats)} dishes in {len(cats)} sections written to index.html")
